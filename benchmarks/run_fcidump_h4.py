"""Reproduce the committed H4 CAS(4e,4o) FCIDUMP benchmark.

This is the first materials-facing rung whose *input* is a frozen interchange
artifact rather than a model regenerated by PySCF at runtime.  The benchmark
therefore needs only the core NumPy installation:

    python benchmarks/run_fcidump_h4.py
    python benchmarks/run_fcidump_h4.py --out result.json

Three paths are kept distinct:

* the committed PySCF determinant-space FCI number is external provenance;
* ``SectorStatevectorBackend`` is the exact oracle for the mapped Hamiltonian;
* A-CASE is scored at a predeclared adaptive budget and with the complete
  singles/doubles coordinate space.

The adaptive record reports both basis size and measurement-word growth.  The
complete singles/doubles solve uses the fast contraction route and labels its
support as untracked; it is an accuracy comparison, not a resource claim.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

from clifford_qc.backends import ExactMVBackend, SectorStatevectorBackend
from clifford_qc.models import fcidump_model
from clifford_qc.reproducibility import stamp_record
from clifford_qc.subspace import (
    determinant_excitations,
    identity_generator,
    occupied_spin_orbitals,
    run_acase,
    solve_subspace,
)

ROOT = Path(__file__).resolve().parent
FCIDUMP = ROOT / "data" / "h4_sto3g_r0.9.FCIDUMP"
PROVENANCE = ROOT / "data" / "h4_sto3g_r0.9.provenance.json"
ADAPTIVE_ADDITIONS = 8
CHEMICAL_ACCURACY_HARTREE = 1.6e-3


def build_record() -> dict:
    provenance = json.loads(PROVENANCE.read_text(encoding="utf-8"))
    reference = provenance["reference_energies"]
    model = fcidump_model(FCIDUMP, name=provenance["name"])
    if model.metadata["source_sha256"] != provenance["fcidump_sha256"]:
        raise ValueError("FCIDUMP digest disagrees with its provenance record")

    rho = ExactMVBackend().state(model.reference, ())
    hf_energy = ExactMVBackend().expectation(
        model.reference, model.hamiltonian, ())
    sector = SectorStatevectorBackend(
        model.n, model.metadata["n_electrons"], model.metadata["sz"])
    exact_values, _ = sector.ground_state(
        model.hamiltonian, k=4, method="dense")
    exact_energy = float(exact_values[0])
    if abs(hf_energy - reference["rhf"]) > 1e-10:
        raise ValueError("mapped Hartree-Fock energy disagrees with provenance")
    if abs(exact_energy - reference["fci"]) > 1e-10:
        raise ValueError("sector-exact energy disagrees with external FCI provenance")

    occupied = occupied_spin_orbitals(model)
    candidates = determinant_excitations(model.n, occupied, max_rank=2)
    adaptive = run_acase(
        rho,
        model.hamiltonian,
        candidates,
        max_size=ADAPTIVE_ADDITIONS,
        leakage_tol=1e-10,
        exact_ground_energy=exact_energy,
    )
    complete = solve_subspace(
        rho,
        model.hamiltonian,
        [identity_generator(model.n), *candidates],
        track_support=False,
    )

    adaptive_error = adaptive.result.ground_energy - exact_energy
    complete_error = complete.ground_energy - exact_energy
    resources = adaptive.result.resources
    return {
        "schema": "clifford_qc.active_space_result.v1",
        "input": {
            "path": FCIDUMP.relative_to(ROOT.parent).as_posix(),
            "sha256": model.metadata["source_sha256"],
            "provenance_schema": provenance["schema"],
            "generator": provenance["generator"],
        },
        "system": {
            "name": model.name,
            "n_qubits": model.n,
            "n_electrons": model.metadata["n_electrons"],
            "sz": model.metadata["sz"],
            "sector_dimension": sector.dimension,
            "hamiltonian_terms": len(model.hamiltonian.terms),
            "candidate_generators": len(candidates),
            "energy_unit": model.metadata["energy_unit"],
        },
        "independent_reference": {
            "method": "PySCF determinant-space FCI",
            "rhf_energy": reference["rhf"],
            "fci_energy": reference["fci"],
        },
        "mapped_oracle": {
            "method": "exact dense solve in the (N=4, Sz=0) sector",
            "ground_energy": exact_energy,
            "external_fci_error": exact_energy - reference["fci"],
            "lowest_four_energies": [float(value) for value in exact_values],
        },
        "adaptive_acase": {
            "method": "Adaptive Clifford-Algebra Subspace Eigensolver",
            "predeclared_additions": ADAPTIVE_ADDITIONS,
            "basis_size": adaptive.basis_size,
            "effective_rank": adaptive.result.effective_rank,
            "condition_number": adaptive.result.condition_number,
            "ground_energy": adaptive.result.ground_energy,
            "error_hartree": adaptive_error,
            "error_millihartree": 1000.0 * adaptive_error,
            "chemical_accuracy": adaptive_error <= CHEMICAL_ACCURACY_HARTREE,
            "labels": list(adaptive.labels),
            "energy_history": list(adaptive.energy_history),
            "word_universe": resources["word_universe"],
            "max_generator_support": resources["max_generator_support"],
            "max_hamiltonian_element_support": resources[
                "max_hamiltonian_element_support"],
            "cached_operator_bytes": resources["cached_operator_bytes"],
        },
        "complete_singles_doubles": {
            "method": "fixed complete determinant singles/doubles",
            "basis_size": len(complete.basis_labels),
            "effective_rank": complete.effective_rank,
            "condition_number": complete.condition_number,
            "ground_energy": complete.ground_energy,
            "error_hartree": complete_error,
            "error_millihartree": 1000.0 * complete_error,
            "chemical_accuracy": complete_error <= CHEMICAL_ACCURACY_HARTREE,
            "support_tracked": False,
        },
        "evidence": {
            "energies": "exact",
            "adaptive_selection": "exact",
            "resource_counts": "exact",
            "quantum_advantage_claim": False,
        },
    }


def main(argv=None) -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path)
    args = parser.parse_args(argv)
    record = stamp_record(build_record())
    rendered = json.dumps(record, indent=2, sort_keys=True) + "\n"
    if args.out is not None:
        args.out.parent.mkdir(parents=True, exist_ok=True)
        args.out.write_text(rendered, encoding="utf-8")

    adaptive = record["adaptive_acase"]
    complete = record["complete_singles_doubles"]
    system = record["system"]
    print(f"{system['name']}: {system['n_qubits']} qubits, "
          f"sector dimension {system['sector_dimension']}")
    print(f"external/sector FCI: "
          f"{record['mapped_oracle']['ground_energy']:+.12f} hartree")
    print(f"adaptive A-CASE:     {adaptive['ground_energy']:+.12f} hartree, "
          f"M={adaptive['basis_size']}, W={adaptive['word_universe']}, "
          f"error={adaptive['error_millihartree']:.6f} mHa")
    print(f"complete SD:         {complete['ground_energy']:+.12f} hartree, "
          f"M={complete['basis_size']}, "
          f"error={complete['error_millihartree']:.6f} mHa")


if __name__ == "__main__":
    main()
