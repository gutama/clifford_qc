def main() -> int:
    if not SUMMARY.exists():
        print(f"missing {SUMMARY}; run `python -m molecular.run --output-directory molecular/results`")
        return 1
    summary = json.loads(SUMMARY.read_text())
    MD.write_text(render_markdown(summary))
    TEX.write_text(render_tex(summary))
    print(f"wrote {MD.relative_to(ROOT)} and {TEX.relative_to(ROOT)} "
          f"from {len(summary)} molecules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
