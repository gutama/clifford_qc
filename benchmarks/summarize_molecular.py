"""Generate the molecular simulation report from the committed records.

The report used to be maintained by hand beside the JSON it described. That is
the same defect class ``check_summaries.py`` exists to prevent elsewhere in the
repository, and it failed the same way: three fields were edited into the
record, the report's tables were updated from them, and every consistency
partner -- effective rank, the Ritz vectors, the observables -- was left
describing an earlier run. A malformed table row survived several commits for
the same reason.

So the tables are derived, not transcribed. Prose that makes a claim about a
number reads that number from the record.

    python benchmarks/summarize_molecular.py

Writes ``molecular/report.md`` and ``molecular/report.tex``.
Run ``benchmarks/check_molecular.py`` first; this script assumes the record is
already self-consistent and will happily typeset a contradiction.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "molecular/results"
SUMMARY = RESULTS / "results_summary.json"
MD = ROOT / "molecular/report.md"
TEX = ROOT / "molecular/report.tex"

CHEMICAL_ACCURACY_MHA = 1.5936

DISPLAY = {
    "lih": ("LiH", r"\text{LiH}", "LiH"),
    "beh2": ("BeH₂", r"\text{BeH}_2", "BeH$_2$"),
    "hf": ("HF", r"\text{HF}", "HF"),
    "h2o": ("H₂O", r"\text{H}_2\text{O}", "H$_2$O"),
    "lih_stretched": ("LiH 3×", r"\text{LiH}", r"LiH 3$\times$"),
    "beh2_stretched": ("BeH₂ 2×", r"\text{BeH}_2", r"BeH$_2$ 2$\times$"),
    "h2o_stretched": ("H₂O 2×", r"\text{H}_2\text{O}", r"H$_2$O 2$\times$"),
    "h2o_dissociating": ("H₂O 2.5×", r"\text{H}_2\text{O}", r"H$_2$O 2.5$\times$"),
}

GEOMETRY = {
    "lih": "Li--H 1.595 Å",
    "beh2": "linear, Be--H 1.326 Å",
    "hf": "H--F 0.917 Å",
    "h2o": "O--H 0.9575 Å, ∠HOH 104.51°",
    "lih_stretched": "Li--H 4.785 Å (3× rₑ), control",
    "beh2_stretched": "symmetric, Be--H 2.652 Å (2× rₑ)",
    "h2o_stretched": "symmetric, O--H 1.9150 Å (2× rₑ)",
    "h2o_dissociating": "symmetric, O--H 2.3938 Å (2.5× rₑ)",
}


def _md_name(key: str) -> str:
    return DISPLAY[key][0]


def _tex_name(key: str) -> str:
    return DISPLAY[key][2]


def master_rows(summary: dict) -> list[dict]:
    rows = []
    for key, r in summary.items():
        rows.append({
            "key": key,
            "n": r["qubits"],
            "ne": r["n_electrons"],
            "sector": r["sector_dimension"],
            "rhf": r["e_rhf"],
            "ccsd": r["e_ccsd"],
            "ccsd_err": r["error_ccsd_mha"],
            "cisd": r.get("e_cisd_determinant", r.get("e_sd_complete")),
            "cisd_err": r.get("error_cisd_determinant_mha",
                              r.get("error_sd_mha")),
            "cisd_pyscf_ok": r.get("cisd_pyscf_agrees", True),
            "regime": r.get("regime", "equilibrium"),
            "ccsd_low": r.get("ccsd_below_exact", False),
            "sd_run": r.get("complete_sd_run", True),
            "exact": r["e_exact_fci"],
            "ad": r["e_acase_adaptive"],
            "ad_err": r["error_adaptive_mha"],
            "ad_m": r["subspace_size_m"],
            "kappa": r["condition_number"],
            "sd": r["e_sd_complete"],
            "sd_err": r["error_sd_mha"],
            "sd_m": r["complete_sd_basis_size"],
            "sd_det": r.get("sd_determinant_count"),
            "sd_full": r["sd_spans_full_sector"],
            "oracle": r["adaptive_oracle_stop_used"],
            "d": r["double_occupancy"],
            "d_hf": r["double_occupancy_uncorrelated"],
            "s2": r["total_spin_squared"],
            "ham_terms": r["hamiltonian_pauli_terms"],
            "universe": r["element_word_universe"],
            "sd_seconds": r.get("sd_subspace_seconds"),
            "seconds": r["elapsed_seconds"],
            "ad_seconds": r["adaptive_seconds"],
            "ad_bytes": r["adaptive_cached_operator_bytes"],
            "ad_rss": r["adaptive_peak_rss_bytes"],
            "sd_rss": r.get("sd_peak_rss_bytes"),
            "sd_rss_delta": r.get("sd_peak_rss_delta_bytes"),
            "ad_products": r["adaptive_operator_products"],
            "ad_pairs": r["adaptive_pairs_built"],
            "response": r["response_diagnostic"],
            "stop": r["adaptive_stop_reason"],
        })
    return rows


def render_markdown(summary: dict) -> str:
    rows = master_rows(summary)
    any_oracle = any(r["oracle"] for r in rows)
    L: list[str] = []
    add = L.append

    add("# Molecular benchmark report: LiH, BeH₂, HF, and H₂O through `clifford_qc` A-CASE")
    add("")
    add("*Generated by `benchmarks/summarize_molecular.py` from "
        "`molecular/results/results_summary.json`. Do not edit by hand — "
        "regenerate. Consistency is gated by `benchmarks/check_molecular.py`.*")
    add("")
    add("## Abstract")
    add("")
    add("Four closed-shell molecules in STO-3G are carried through the full "
        "chain — PySCF RHF → FCIDUMP → Jordan–Wigner → A-CASE — and scored "
        "against the exact ground state of the reference's own particle-number "
        "and $S_z$ sector. The adaptive subspace is the result under test; "
        "CCSD, CISD, the complete singles-and-doubles subspace, and sector-exact "
        "diagonalization are the baselines it is measured against.")
    add("")
    add("---")
    add("")
    add("## 1. Results")
    add("")
    add("### 1.1 Adaptive A-CASE against classical baselines")
    add("")
    add("Errors in mHa against the sector-exact ground energy; chemical accuracy "
        f"is {CHEMICAL_ACCURACY_MHA} mHa.")
    add("")
    add("CISD here is the **determinant-space** minimum computed in this "
        "repository, not PySCF's. At H₂O 2.5× PySCF returns an energy 55.2 mHa "
        "above the minimum of its own space while reporting convergence; it "
        "agrees to nine digits everywhere else. See §1.3.")
    add("")
    for regime, title in (("equilibrium", "Equilibrium"),
                          ("stretched", "Stretched")):
        group = [r for r in rows if r["regime"] == regime]
        if not group:
            continue
        add(f"**{title}**")
        add("")
        add("| Geometry | $n$ | Sector | A-CASE $M$ | A-CASE | CCSD | CISD | "
            "$\\kappa(S)$ |")
        add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
        for r in group:
            mark = " ‡" if r["ccsd_low"] else (" †" if r["sd_full"] else "")
            add(f"| **{_md_name(r['key'])}** | {r['n']} | {r['sector']} "
                f"| {r['ad_m']} | `{r['ad_err']:+.3f}` "
                f"| `{r['ccsd_err']:+.3f}`{mark} | `{r['cisd_err']:+.3f}` "
                f"| `{r['kappa']:.2f}` |")
        add("")

    beaten = [r for r in rows if abs(r["ccsd_err"]) < abs(r["ad_err"])]
    low = [r for r in rows if r["ccsd_low"]]
    ceiling = [r for r in rows
               if abs(r["ad_err"] - r["cisd_err"]) < 1.0 and r["cisd_err"] > 5.0]
    add("**What the table says, in both directions.**")
    add("")
    add(f"*Against the method.* CCSD is more accurate on {len(beaten)} of "
        f"{len(rows)} geometries, at a small fraction of the cost — "
        "milliseconds against minutes. Stretching does not open a niche: on "
        + ", ".join(_md_name(r["key"]) for r in ceiling) +
        " the A-CASE error sits within 1 mHa of the CISD ceiling it cannot "
        "pass, because its candidate family *is* singles and doubles, so its "
        "span is a subspace of the CISD space. The binding constraint is the "
        "excitation family, not the geometry — the same conclusion "
        "`PLAN.md` drew from H₄ and the Hubbard clusters, now "
        "reproduced on molecular chemistry. What would change it is level-4 "
        "generators (competing-order configurations dressed by excitations), "
        "not more geometries.")
    add("")
    if low:
        add("*For the method, narrowly.* ‡ On "
            + " and ".join(_md_name(r["key"]) for r in low) +
            " CCSD lands **below** the exact energy — it is not variational, "
            "and under strong static correlation it forfeits the one guarantee "
            "a Rayleigh–Ritz subspace keeps structurally. An error bar is worth "
            "less when its sign is not known.")
        add("")
    add("*The LiH 3× row is a control and behaves like one*: a stretched "
        "geometry where CCSD still wins comfortably. A single σ bond in a "
        "minimal basis stays single-reference, so any claim that stretching "
        "favours A-CASE has to survive it.")
    add("")
    add("### 1.2 Where the complete-SD arm ran")
    add("")
    add("| Geometry | Complete SD $M$ | SD err | SD determinants |")
    add("| :--- | ---: | ---: | ---: |")
    for r in rows:
        if r["sd_run"]:
            note = " †" if r["sd_full"] else ""
            add(f"| {_md_name(r['key'])} | {r['sd_m']}{note} "
                f"| `{r['sd_err']:+.4f}` | — |")
        else:
            add(f"| {_md_name(r['key'])} | skipped | — | {r['sd_det']} |")
    add("")
    add("The arm reproduces CISD by construction, so it is skipped on the "
        "stretched rows and the determinant CISD is diagonalized directly "
        "instead — a 141×141 problem in milliseconds against the half hour the "
        "element-operator route needs for the same number.")
    add("")
    add("### 1.3 PySCF as a cross-check, not an oracle")
    add("")
    bad = [r for r in rows if not r["cisd_pyscf_ok"]]
    if bad:
        for r in bad:
            add(f"- **{_md_name(r['key'])}**: PySCF CISD misses the minimum of "
                f"its own space. Caught because A-CASE — a *subspace* of that "
                f"space — came out below it, which is impossible; "
                f"`check_molecular.py` now tests that inequality directly.")
    else:
        add("- PySCF CISD agrees with the determinant minimum on every row.")
    add("")
    full = [r for r in rows if r["sd_full"]]
    if full:
        names = ", ".join(_md_name(r["key"]) for r in full)
        add(f"† The complete SD basis already spans the entire sector for "
            f"{names} ({full[0]['sd_m']} vectors against a "
            f"{full[0]['sector']}-state sector), so agreement with sector-exact "
            f"diagonalization "
            f"there is arithmetic rather than accuracy — there is nothing left "
            f"to miss. CCSD is converged to the same energy on that row by the "
            f"same combinatorial fact: with only two holes, singles and doubles "
            f"exhaust the excitation manifold, so CCSD is exact for the system "
            f"rather than accurate on it.")
        add("")
    add("**The complete SD subspace reproduces CISD**, as it must: a linear span "
        "of the identity and all single and double excitations on a Hartree–Fock "
        "reference *is* the CISD space. The agreement below is a correctness "
        "check on the Jordan–Wigner construction and the projected eigensolver, "
        "not evidence about A-CASE.")
    add("")
    add("| Molecule | Complete SD $E_0$ (Ha) | PySCF CISD (Ha) | difference (Ha) |")
    add("| :--- | ---: | ---: | ---: |")
    for r in rows:
        if not r["sd_run"]:
            continue
        add(f"| {_md_name(r['key'])} | `{r['sd']:.9f}` | `{r['cisd']:.9f}` "
            f"| `{r['sd'] - r['cisd']:+.2e}` |")
    add("")
    add("### 1.4 Full energies")
    add("")
    add("| Molecule | RHF | CCSD | CISD | Complete SD | A-CASE | Sector-exact FCI |")
    add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        sd = f"`{r['sd']:.9f}`" if r["sd_run"] else "—"
        add(f"| {_md_name(r['key'])} | `{r['rhf']:.9f}` | `{r['ccsd']:.9f}` "
            f"| `{r['cisd']:.9f}` | {sd} | `{r['ad']:.9f}` "
            f"| `{r['exact']:.9f}` |")
    add("")
    add("---")
    add("")
    add("## 2. Observables")
    add("")
    add("Every number here is read off the *same* solve that produced the "
        "adaptive energy above, through the projected-observable route "
        "($Q_{sub}$ contracted with the Ritz coefficients) — no Ritz state is "
        "materialized. The coupling matters: a record whose observables came "
        "from a different run than its energies described a wavefunction that "
        "could not have produced that energy.")
    add("")
    add("| Molecule | $\\langle d \\rangle$ | uncorrelated $\\langle d \\rangle$ "
        "| correlation visible | $\\langle S^2 \\rangle$ |")
    add("| :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        delta = r["d"] - r["d_hf"]
        add(f"| {_md_name(r['key'])} | `{r['d']:.9f}` | `{r['d_hf']:.9f}` "
            f"| `{delta:+.2e}` | `{r['s2']:.2e}` |")
    add("")
    add("The uncorrelated column is $N_e/(2n_{\\text{orb}})$, the closed-shell "
        "reference value. The difference diagnoses changes in orbital double "
        "occupancy; equality alone does not prove the state is uncorrelated.")
    add("")
    add("$\\langle S^2 \\rangle$ checks spin contamination. Conserving $S_z$ "
        "does not enforce a singlet: the selected determinant subspace need not "
        "preserve total spin. Nonzero values, especially stretched water's, "
        "must be assessed before comparing states of different multiplicity.")
    add("")
    add("### 2.1 Response limitations")
    add("")
    add("The site-0 $S_z$ Lehmann response is computed only within the selected "
        "Ritz space. Negligible projected weight does not establish a vanishing "
        "physical susceptibility. The historical diagnostics below are preserved "
        "verbatim; their claim that the excitation basis preserves singlets is "
        "not guaranteed by $S_z$ conservation and is superseded by this caveat.")
    add("")
    for r in rows:
        add(f"- **{_md_name(r['key'])}**: {r['response']}")
    add("")
    add("A physical response claim would require checking the relevant excited "
        "spin sectors and convergence of their transition weights. This suite "
        "does not perform that validation.")
    add("")
    add("---")
    add("")
    add("## 3. Resource accounting")
    add("")
    add("Two different word counts appear in A-CASE work and they must not be "
        "conflated. **Distinct Pauli words in $H$** is the size of the "
        "Hamiltonian's own support after word-code collection. **Element word "
        "universe** is "
        "$|\\bigcup_{ij} \\mathrm{supp}(A_i^\\dagger A_j) \\cup "
        "\\mathrm{supp}(A_i^\\dagger H A_j)|$ — the union over element "
        "operators, legitimately far larger because those are triple products. "
        "Reporting the second under the first's name inflates the apparent "
        "Hamiltonian cost by roughly two orders of magnitude.")
    add("")
    add("| Molecule | Distinct Pauli words in $H$ | Element word universe | "
        "A-CASE $M$ | Complete SD wall-clock (s) |")
    add("| :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        secs = f"{r['sd_seconds']:.1f}" if r["sd_run"] else "—"
        add(f"| {_md_name(r['key'])} | {r['ham_terms']} | {r['universe']:,} "
            f"| {r['ad_m']} | {secs} |")
    add("")
    add("The Hamiltonian counts are the standard literature values for these "
        "systems, and LiH and HF agree exactly because both are six spatial "
        "orbitals on twelve qubits — a structural check that the collection step "
        "is working.")
    add("")
    add("### 3.1 Time and memory")
    add("")
    add("`PLAN.md` §6 asks for bank build time and peak memory "
        "beside basis size, on the grounds that a small basis is not a "
        "compactness result if its projected entries cost gigabytes. The "
        "adaptive figures come from the bank itself; resident set size is "
        "sampled during each arm.")
    add("")
    add("**Read the RSS columns carefully — neither is a clean per-arm cost.** "
        "The molecules run sequentially in one process, and freed memory "
        "returns to the operating system only partially and unpredictably "
        "(large allocations are unmapped, small ones are retained in allocator "
        "free lists). So *high-water* carries whatever earlier arms left "
        "resident, and the *rise*, measured against the arm's own starting "
        "point, is a **lower bound** — an arm served entirely from free lists "
        "grows no new mappings at all. The arm's true cost lies between them, "
        "and the interval can be wide enough to be uninformative: in this run "
        "one arm records a rise of exactly zero beside a high-water above "
        "5 GiB.")
    add("")
    add("| Molecule | A-CASE $M$ | A-CASE time (s) | A-CASE cached ops | "
        "SD $M$ | SD time (s) | SD RSS rise | RSS high-water |")
    add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        if r["sd_run"]:
            sd_cols = (f"{r['sd_m']} | {r['sd_seconds']:.1f} "
                       f"| {r['sd_rss_delta'] / 2**30:.2f} GiB "
                       f"| {r['sd_rss'] / 2**30:.2f} GiB")
        else:
            sd_cols = "skipped | — | — | —"
        add(f"| {_md_name(r['key'])} | {r['ad_m']} | {r['ad_seconds']:.1f} "
            f"| {r['ad_bytes'] / 2**20:.1f} MiB | {sd_cols} |")
    add("")
    add("`A-CASE cached ops` is the bank's own estimate of the bytes held by "
        "its cached element operators — an attributable per-arm figure, unlike "
        "the RSS columns, and the one to compare across molecules.")
    add("")
    worst = max((r for r in rows if r["sd_run"]),
                key=lambda r: r["sd_rss"])
    add(f"The complete-SD wall clock is dominated by the element-operator "
        f"route, which costs $O(|A_i|\\,|H|\\,|A_j|)$ per pair over $M(M+1)/2$ "
        f"pairs and caches every one. On {_md_name(worst['key'])} that is "
        f"{worst['sd_m'] * (worst['sd_m'] + 1) // 2:,} element operators and "
        f"{worst['sd_rss'] / 2**30:.2f} GiB resident for a "
        f"{worst['sd_m']}-vector basis — which is the resource statement §6 "
        f"asks for, and the strongest argument in this dataset for the cyclic "
        f"contraction $\\mathrm{{Tr}}((HA_j)(\\rho A_i^\\dagger))$ at $2M$ "
        f"products and $M^2$ pairings instead. What that route gives up is the "
        f"support metrics the element route makes observable.")
    add("")
    add("The adaptive arm uses fewer selected directions, "
        "by retaining a smaller selected block; screening can still build pairs for rejected candidates.")
    add("")
    add("---")
    add("")
    add("## 4. Systems")
    add("")
    add("| Molecule | Geometry | Basis | $n$ | $N_e$ | $S_z$ | Sector dimension |")
    add("| :--- | :--- | :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        add(f"| {_md_name(r['key'])} | {GEOMETRY[r['key']]} | STO-3G | {r['n']} "
            f"| {r['ne']} | 0 | {r['sector']} |")
    add("")
    add("---")
    add("")
    add("## 5. Reproducing")
    add("")
    add("```bash")
    add("python -m molecular.run --output-directory molecular/results           # regenerate the records")
    add("python benchmarks/check_molecular.py       # gate their consistency")
    add("python benchmarks/summarize_molecular.py   # regenerate this report")
    add("```")
    add("")
    add("Records, FCIDUMPs and per-molecule JSON are in "
        "[`molecular/results/`](results/).")
    add("")
    return "\n".join(L) + "\n"


def render_tex(summary: dict) -> str:
    rows = master_rows(summary)
    L: list[str] = []
    add = L.append

    add(r"\documentclass[11pt]{article}")
    add(r"\usepackage[margin=1in]{geometry}")
    add(r"\usepackage{amsmath,amssymb}")
    add(r"\usepackage{booktabs}")
    add(r"\usepackage{graphicx}")
    add(r"\usepackage{hyperref}")
    add(r"\title{Molecular benchmark report: LiH, BeH$_2$, HF, and H$_2$O"
        "\\\\ through \\texttt{clifford\\_qc} A-CASE}")
    add(r"\date{\today}")
    add(r"\begin{document}")
    add(r"\maketitle")
    add("")
    add(r"\noindent\emph{Generated by \path{benchmarks/summarize_molecular.py}"
        r".}\par\noindent\emph{Source: \path{molecular/results/results_summary.json}. Do not edit by"
        r" hand.}")
    add("")
    add(r"\section{Results}")
    add("")
    add(r"Errors in mHa against the sector-exact ground energy of the reference's"
        r" own $(N, S_z)$ sector; chemical accuracy is "
        f"{CHEMICAL_ACCURACY_MHA} mHa.")
    add("")
    add(r"\begin{table}[h]")
    add(r"\centering")
    add(r"\caption{Adaptive A-CASE against classical baselines.}")
    add(r"\resizebox{\textwidth}{!}{%")
    add(r"\begin{tabular}{lrrrrrrrrr}")
    add(r"\toprule")
    add(r"Molecule & $n$ & $N_e$ & Sector & $M$ & A-CASE & CCSD & CISD & SD & "
        r"$\kappa(S)$ \\")
    add(r" & & & dim & & (mHa) & (mHa) & (mHa) & (mHa) & \\")
    add(r"\midrule")
    for r in rows:
        note = r"$^\dagger$" if r["sd_full"] else ""
        sd_col = f"${r['sd_err']:+.4f}${note}" if r["sd_run"] else "---"
        add(f"{_tex_name(r['key'])} & {r['n']} & {r['ne']} & {r['sector']} & "
            f"{r['ad_m']} & ${r['ad_err']:+.4f}$ & ${r['ccsd_err']:+.4f}$ & "
            f"${r['cisd_err']:+.4f}$ & {sd_col} & "
            f"${r['kappa']:.2f}$ \\\\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add("}")
    add(r"\end{table}")
    add("")
    beaten = [r for r in rows if abs(r["ccsd_err"]) < abs(r["ad_err"])]
    accurate = [r for r in rows if abs(r["ad_err"]) <= CHEMICAL_ACCURACY_MHA]
    add(r"\noindent\textbf{Reading the table.} A-CASE reaches chemical accuracy "
        f"on {len(accurate)} of {len(rows)} geometries. CCSD has a smaller absolute "
        f"error on {len(beaten)} of {len(rows)} geometries. Negative CCSD errors "
        "are possible because coupled cluster is not variational. Some capped "
        "stretched runs miss chemical accuracy; inspect their errors "
        "and spin contamination alongside basis size.")
    add("")
    if any(r["oracle"] for r in rows):
        add(r"\noindent\textbf{The stopping rule is oracle-assisted.} Where enabled, "
            r"growth may halt when the error against the \emph{exact} energy falls "
            r"below threshold. Runs may also terminate at a budget or another "
            r"stopping condition. The $M$ column is the selected basis size, not "
            r"a guarantee that the accuracy target was reached.")
        add("")
    if any(r["sd_full"] for r in rows):
        add(r"\noindent$^\dagger$ The complete SD basis spans the entire sector "
            r"for this molecule, so agreement with exact diagonalization is "
            r"arithmetic rather than accuracy.")
        add("")
    add(r"\section{Observables}")
    add("")
    add(r"Read off the same solve that produced the adaptive energy, through the "
        r"projected-observable route; no Ritz state is materialized.")
    add("")
    add(r"\begin{table}[h]")
    add(r"\centering")
    add(r"\caption{Double occupancy against its uncorrelated value, and the "
        r"singlet check.}")
    add(r"\begin{tabular}{lrrrr}")
    add(r"\toprule")
    add(r"Molecule & $\langle d \rangle$ & uncorrelated & difference & "
        r"$\langle S^2 \rangle$ \\")
    add(r"\midrule")
    for r in rows:
        add(f"{_tex_name(r['key'])} & ${r['d']:.9f}$ & ${r['d_hf']:.9f}$ & "
            f"${r['d'] - r['d_hf']:+.2e}$ & ${r['s2']:.2e}$ \\\\")
