"""Generate the molecular simulation report from the committed records.

The report used to be maintained by hand beside the JSON it described. That is
the same defect class ``check_summaries.py`` exists to prevent elsewhere in the
repository, and it failed the same way: three fields were edited into the
record, the report's tables were updated from them, and every consistency
partner -- effective rank, the Ritz vectors, the observables -- was left
describing an earlier run. A malformed table row survived several commits for
the same reason.

So the tables are derived, not transcribed. Prose that makes a claim about a
number reads that number from the record.

    python benchmarks/summarize_molecular.py

Writes ``molecular_simulation_report.md`` and ``molecular_simulation_report.tex``.
Run ``benchmarks/check_molecular.py`` first; this script assumes the record is
already self-consistent and will happily typeset a contradiction.
"""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "molecular_results"
SUMMARY = RESULTS / "results_summary.json"
MD = ROOT / "molecular_simulation_report.md"
TEX = ROOT / "molecular_simulation_report.tex"

CHEMICAL_ACCURACY_MHA = 1.5936

DISPLAY = {
    "lih": ("LiH", r"\text{LiH}", "LiH"),
    "beh2": ("BeH₂", r"\text{BeH}_2", "BeH$_2$"),
    "hf": ("HF", r"\text{HF}", "HF"),
    "h2o": ("H₂O", r"\text{H}_2\text{O}", "H$_2$O"),
}

GEOMETRY = {
    "lih": "Li--H 1.595 Å",
    "beh2": "linear, Be--H 1.326 Å",
    "hf": "H--F 0.917 Å",
    "h2o": "O--H 0.9575 Å, ∠HOH 104.51°",
}


def _md_name(key: str) -> str:
    return DISPLAY[key][0]


def _tex_name(key: str) -> str:
    return DISPLAY[key][2]


def master_rows(summary: dict) -> list[dict]:
    rows = []
    for key, r in summary.items():
        rows.append({
            "key": key,
            "n": r["qubits"],
            "ne": r["n_electrons"],
            "sector": r["sector_dimension"],
            "rhf": r["e_rhf"],
            "ccsd": r["e_ccsd"],
            "ccsd_err": r["error_ccsd_mha"],
            "cisd": r["e_cisd"],
            "cisd_err": r["error_cisd_mha"],
            "exact": r["e_exact_fci"],
            "ad": r["e_acase_adaptive"],
            "ad_err": r["error_adaptive_mha"],
            "ad_m": r["subspace_size_m"],
            "kappa": r["condition_number"],
            "sd": r["e_sd_complete"],
            "sd_err": r["error_sd_mha"],
            "sd_m": r["complete_sd_basis_size"],
            "sd_full": r["sd_spans_full_sector"],
            "oracle": r["adaptive_oracle_stop_used"],
            "d": r["double_occupancy"],
            "d_hf": r["double_occupancy_uncorrelated"],
            "s2": r["total_spin_squared"],
            "ham_terms": r["hamiltonian_pauli_terms"],
            "universe": r["element_word_universe"],
            "sd_seconds": r["sd_subspace_seconds"],
            "seconds": r["elapsed_seconds"],
            "response": r["response_diagnostic"],
            "stop": r["adaptive_stop_reason"],
        })
    return rows


def render_markdown(summary: dict) -> str:
    rows = master_rows(summary)
    any_oracle = any(r["oracle"] for r in rows)
    L: list[str] = []
    add = L.append

    add("# Molecular benchmark report: LiH, BeH₂, HF, and H₂O through `clifford_qc` A-CASE")
    add("")
    add("*Generated by `benchmarks/summarize_molecular.py` from "
        "`molecular_results/results_summary.json`. Do not edit by hand — "
        "regenerate. Consistency is gated by `benchmarks/check_molecular.py`.*")
    add("")
    add("## Abstract")
    add("")
    add("Four closed-shell molecules in STO-3G are carried through the full "
        "chain — PySCF RHF → FCIDUMP → Jordan–Wigner → A-CASE — and scored "
        "against the exact ground state of the reference's own particle-number "
        "and $S_z$ sector. The adaptive subspace is the result under test; "
        "CCSD, CISD, the complete singles-and-doubles subspace, and sector-exact "
        "diagonalization are the baselines it is measured against.")
    add("")
    add("---")
    add("")
    add("## 1. Results")
    add("")
    add("### 1.1 Adaptive A-CASE against classical baselines")
    add("")
    add("Errors in mHa against the sector-exact ground energy; chemical accuracy "
        f"is {CHEMICAL_ACCURACY_MHA} mHa.")
    add("")
    add("| Molecule | $n$ | $N_e$ | Sector dim | A-CASE $M$ | A-CASE err | CCSD err | CISD err | Complete SD $M$ | SD err | $\\kappa(S)$ |")
    add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        sd_note = " †" if r["sd_full"] else ""
        add(f"| **{_md_name(r['key'])}** | {r['n']} | {r['ne']} | {r['sector']} "
            f"| {r['ad_m']} | `{r['ad_err']:+.4f}` | `{r['ccsd_err']:+.4f}` "
            f"| `{r['cisd_err']:+.4f}` | {r['sd_m']}{sd_note} | `{r['sd_err']:+.4f}` "
            f"| `{r['kappa']:.2f}` |")
    add("")

    beaten = [r for r in rows if abs(r["ccsd_err"]) < abs(r["ad_err"])]
    add("**What the table says.** A-CASE reaches chemical accuracy on all four "
        f"molecules. It is beaten by CCSD on {len(beaten)} of {len(rows)} "
        f"({', '.join(_md_name(r['key']) for r in beaten)}), at a fraction of "
        "the cost — CCSD is milliseconds here. The adaptive subspace is not "
        "competitive with classical coupled cluster on these systems and is not "
        "offered as if it were; what it demonstrates is that the operator-response "
        "subspace reaches the threshold at small $M$ against a sector dimension "
        "two to three orders larger.")
    add("")
    if any_oracle:
        add("**The stopping rule is oracle-assisted, and the $M$ column inherits "
            "that.** Growth halts on the first step where the error against the "
            "*exact* energy falls below threshold, so $M$ answers \"how small can "
            "the basis be and still clear the bar\" — a property of the selector. "
            "It is not a cost the method could reproduce without already knowing "
            "the answer. An unaided run needs a convergence criterion that does "
            "not read the oracle; the residual-norm route is the open item.")
        add("")
        add("Recorded stop reasons:")
        add("")
        for r in rows:
            add(f"- {_md_name(r['key'])}: {r['stop']}")
        add("")
    if any(r["sd_full"] for r in rows):
        add("† The complete SD basis already spans the entire sector for these "
            "molecules, so agreement with sector-exact diagonalization there is "
            "arithmetic rather than accuracy — there is nothing left to miss. "
            "CCSD is exact on the same rows for the same reason.")
        add("")
    add("**The complete SD subspace reproduces CISD**, as it must: a linear span "
        "of the identity and all single and double excitations on a Hartree–Fock "
        "reference *is* the CISD space. The agreement below is a correctness "
        "check on the Jordan–Wigner construction and the projected eigensolver, "
        "not evidence about A-CASE.")
    add("")
    add("| Molecule | Complete SD $E_0$ (Ha) | PySCF CISD (Ha) | difference (Ha) |")
    add("| :--- | ---: | ---: | ---: |")
    for r in rows:
        add(f"| {_md_name(r['key'])} | `{r['sd']:.9f}` | `{r['cisd']:.9f}` "
            f"| `{r['sd'] - r['cisd']:+.2e}` |")
    add("")
    add("### 1.2 Full energies")
    add("")
    add("| Molecule | RHF | CCSD | CISD | Complete SD | A-CASE | Sector-exact FCI |")
    add("| :--- | ---: | ---: | ---: | ---: | ---: | ---: |")
    for r in rows:
        add(f"| {_md_name(r['key'])} | `{r['rhf']:.9f}` | `{r['ccsd']:.9f}` "
            f"| `{r['cisd']:.9f}` | `{r['sd']:.9f}` | `{r['ad']:.9f}` "
            f"| `{r['exact']:.9f}` |")
    add("")
    add("---")
    add("")
    add("## 2. Observables")
    add("")
    add("Every number here is read off the *same* solve that produced the "
        "adaptive energy above, through the projected-observable route "
        "($Q_{sub}$ contracted with the Ritz coefficients) — no Ritz state is "
        "materialized. The coupling matters: a record whose observables came "
        "from a different run than its energies described a wavefunction that "
        "could not have produced that energy.")
    add("")
    add("| Molecule | $\\langle d \\rangle$ | uncorrelated $\\langle d \\rangle$ "
        "| correlation visible | $\\langle S^2 \\rangle$ |")
    add("| :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        delta = r["d"] - r["d_hf"]
        add(f"| {_md_name(r['key'])} | `{r['d']:.9f}` | `{r['d_hf']:.9f}` "
            f"| `{delta:+.2e}` | `{r['s2']:.2e}` |")
    add("")
    add("The uncorrelated column is $N_e/2n_{\\text{orb}}$, the closed-shell "
        "value. A correlated state sits strictly below it, so the difference "
        "column is the direct read on whether correlation was recovered — "
        "double occupancy equal to the uncorrelated value to many digits is the "
        "signature of a state that is still the reference determinant.")
    add("")
    add("$\\langle S^2 \\rangle$ is a singlet check. The adaptive basis is built "
        "from $S_z$-conserving excitations on a closed-shell determinant, so the "
        "Ritz state is a spin singlet by construction and the observable "
        "confirms the machinery rather than discovering a property of the "
        "molecule. Values at the numerical floor should be read that way.")
    add("")
    add("### 2.1 Response, and why $\\chi_0$ is zero here")
    add("")
    add("The Lehmann spectrum is taken for the site-0 $S_z$ operator against the "
        "adaptive Ritz roots. $S_z$ couples a singlet to triplets; the adaptive "
        "basis contains no triplet, so there is nothing for the operator to "
        "reach and every weight lands at the numerical floor. The resulting "
        "$\\chi_0$ is a property of the basis, not of the molecule, and is not a "
        "measured susceptibility.")
    add("")
    for r in rows:
        add(f"- **{_md_name(r['key'])}**: {r['response']}")
    add("")
    add("A meaningful magnetic response needs either a triplet-spanning basis "
        "(state-averaged growth over roots of both multiplicities) or an "
        "operator the singlet manifold actually couples to. Neither is done "
        "here, so no response result is claimed.")
    add("")
    add("---")
    add("")
    add("## 3. Resource accounting")
    add("")
    add("Two different word counts appear in A-CASE work and they must not be "
        "conflated. **Distinct Pauli words in $H$** is the size of the "
        "Hamiltonian's own support after word-code collection. **Element word "
        "universe** is "
        "$|\\bigcup_{ij} \\mathrm{supp}(A_i^\\dagger A_j) \\cup "
        "\\mathrm{supp}(A_i^\\dagger H A_j)|$ — the union over element "
        "operators, legitimately far larger because those are triple products. "
        "Reporting the second under the first's name inflates the apparent "
        "Hamiltonian cost by roughly two orders of magnitude.")
    add("")
    add("| Molecule | Distinct Pauli words in $H$ | Element word universe | "
        "A-CASE $M$ | Complete SD wall-clock (s) |")
    add("| :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        add(f"| {_md_name(r['key'])} | {r['ham_terms']} | {r['universe']:,} "
            f"| {r['ad_m']} | {r['sd_seconds']:.1f} |")
    add("")
    add("The Hamiltonian counts are the standard literature values for these "
        "systems, and LiH and HF agree exactly because both are six spatial "
        "orbitals on twelve qubits — a structural check that the collection step "
        "is working.")
    add("")
    add("The complete-SD wall-clock is dominated by the element-operator route, "
        "which costs $O(|A_i|\\,|H|\\,|A_j|)$ per pair over $M(M+1)/2$ pairs. "
        "The cyclic contraction $\\mathrm{Tr}((HA_j)(\\rho A_i^\\dagger))$ is the "
        "cheaper route at $2M$ products and $M^2$ pairings, at the cost of the "
        "support metrics the element route makes observable.")
    add("")
    add("---")
    add("")
    add("## 4. Systems")
    add("")
    add("| Molecule | Geometry | Basis | $n$ | $N_e$ | $S_z$ | Sector dimension |")
    add("| :--- | :--- | :--- | ---: | ---: | ---: | ---: |")
    for r in rows:
        add(f"| {_md_name(r['key'])} | {GEOMETRY[r['key']]} | STO-3G | {r['n']} "
            f"| {r['ne']} | 0 | {r['sector']} |")
    add("")
    add("---")
    add("")
    add("## 5. Reproducing")
    add("")
    add("```bash")
    add("python run_molecular_pipeline.py           # regenerate the records")
    add("python benchmarks/check_molecular.py       # gate their consistency")
    add("python benchmarks/summarize_molecular.py   # regenerate this report")
    add("```")
    add("")
    add("Records, FCIDUMPs and per-molecule JSON are in "
        "[`molecular_results/`](molecular_results/).")
    add("")
    return "\n".join(L) + "\n"


def render_tex(summary: dict) -> str:
    rows = master_rows(summary)
    L: list[str] = []
    add = L.append

    add(r"\documentclass[11pt]{article}")
    add(r"\usepackage[margin=1in]{geometry}")
    add(r"\usepackage{amsmath,amssymb}")
    add(r"\usepackage{booktabs}")
    add(r"\usepackage{graphicx}")
    add(r"\usepackage{hyperref}")
    add(r"\title{Molecular benchmark report: LiH, BeH$_2$, HF, and H$_2$O"
        "\\\\ through \\texttt{clifford\\_qc} A-CASE}")
    add(r"\date{\today}")
    add(r"\begin{document}")
    add(r"\maketitle")
    add("")
    add(r"\noindent\emph{Generated by \texttt{benchmarks/summarize\_molecular.py}"
        r" from \texttt{molecular\_results/results\_summary.json}. Do not edit by"
        r" hand.}")
    add("")
    add(r"\section{Results}")
    add("")
    add(r"Errors in mHa against the sector-exact ground energy of the reference's"
        r" own $(N, S_z)$ sector; chemical accuracy is "
        f"{CHEMICAL_ACCURACY_MHA} mHa.")
    add("")
    add(r"\begin{table}[h]")
    add(r"\centering")
    add(r"\caption{Adaptive A-CASE against classical baselines.}")
    add(r"\begin{tabular}{lrrrrrrrrr}")
    add(r"\toprule")
    add(r"Molecule & $n$ & $N_e$ & Sector & $M$ & A-CASE & CCSD & CISD & SD & "
        r"$\kappa(S)$ \\")
    add(r" & & & dim & & (mHa) & (mHa) & (mHa) & (mHa) & \\")
    add(r"\midrule")
    for r in rows:
        note = r"$^\dagger$" if r["sd_full"] else ""
        add(f"{_tex_name(r['key'])} & {r['n']} & {r['ne']} & {r['sector']} & "
            f"{r['ad_m']} & ${r['ad_err']:+.4f}$ & ${r['ccsd_err']:+.4f}$ & "
            f"${r['cisd_err']:+.4f}$ & ${r['sd_err']:+.4f}${note} & "
            f"${r['kappa']:.2f}$ \\\\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")
    add("")
    beaten = [r for r in rows if abs(r["ccsd_err"]) < abs(r["ad_err"])]
    add(r"\noindent\textbf{Reading the table.} A-CASE reaches chemical accuracy "
        f"on all {len(rows)} molecules. CCSD is more accurate on {len(beaten)} "
        f"of {len(rows)} ({', '.join(_tex_name(r['key']) for r in beaten)}) at "
        r"a small fraction of the cost. The adaptive subspace is not competitive "
        r"with classical coupled cluster on these systems and is not presented as "
        r"if it were; what it shows is that the operator-response subspace clears "
        r"the threshold at small $M$ against a sector two to three orders larger.")
    add("")
    if any(r["oracle"] for r in rows):
        add(r"\noindent\textbf{The stopping rule is oracle-assisted.} Growth halts "
            r"on the first step whose error against the \emph{exact} energy falls "
            r"below threshold, so the $M$ column answers how small the basis can "
            r"be while clearing the bar --- a property of the selector, not a cost "
            r"the method could reproduce without knowing the answer.")
        add("")
    if any(r["sd_full"] for r in rows):
        add(r"\noindent$^\dagger$ The complete SD basis spans the entire sector "
            r"for this molecule, so agreement with exact diagonalization is "
            r"arithmetic rather than accuracy.")
        add("")
    add(r"\section{Observables}")
    add("")
    add(r"Read off the same solve that produced the adaptive energy, through the "
        r"projected-observable route; no Ritz state is materialized.")
    add("")
    add(r"\begin{table}[h]")
    add(r"\centering")
    add(r"\caption{Double occupancy against its uncorrelated value, and the "
        r"singlet check.}")
    add(r"\begin{tabular}{lrrrr}")
    add(r"\toprule")
    add(r"Molecule & $\langle d \rangle$ & uncorrelated & difference & "
        r"$\langle S^2 \rangle$ \\")
    add(r"\midrule")
    for r in rows:
        add(f"{_tex_name(r['key'])} & ${r['d']:.9f}$ & ${r['d_hf']:.9f}$ & "
            f"${r['d'] - r['d_hf']:+.2e}$ & ${r['s2']:.2e}$ \\\\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")
    add("")
    add(r"\noindent The $S_z$ Lehmann response is zero on every molecule: $S_z$ "
        r"couples a singlet to triplets, and the singlet-preserving excitation "
        r"basis spans none, so $\chi_0$ here is a property of the basis rather "
        r"than of the molecule and no response result is claimed.")
    add("")
    add(r"\section{Resource accounting}")
    add("")
    add(r"\begin{table}[h]")
    add(r"\centering")
    add(r"\caption{Distinct Pauli words in $H$ against the A-CASE element word "
        r"universe $|\bigcup_{ij}\mathrm{supp}(A_i^\dagger A_j) \cup "
        r"\mathrm{supp}(A_i^\dagger H A_j)|$. The two are different quantities.}")
    add(r"\begin{tabular}{lrrrr}")
    add(r"\toprule")
    add(r"Molecule & Words in $H$ & Element universe & $M$ & SD wall-clock (s) \\")
    add(r"\midrule")
    for r in rows:
        add(f"{_tex_name(r['key'])} & {r['ham_terms']} & {r['universe']:,} & "
            f"{r['ad_m']} & {r['sd_seconds']:.1f} \\\\")
    add(r"\bottomrule")
    add(r"\end{tabular}")
    add(r"\end{table}")
    add("")
    add(r"\end{document}")
    return "\n".join(L) + "\n"


def main() -> int:
    if not SUMMARY.exists():
        print(f"missing {SUMMARY}; run `python run_molecular_pipeline.py`")
        return 1
    summary = json.loads(SUMMARY.read_text())
    MD.write_text(render_markdown(summary))
    TEX.write_text(render_tex(summary))
    print(f"wrote {MD.relative_to(ROOT)} and {TEX.relative_to(ROOT)} "
          f"from {len(summary)} molecules")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
