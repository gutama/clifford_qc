"""The matched-shot study's committed records and the tables its document embeds.

These run without PySCF: they read the committed records, never rerun them.
"""

import json

import pytest

from benchmarks import run_matched_shot_commutator_krylov as study

BENCHMARKS = study.ROOT / "benchmarks"
PRIMARY = BENCHMARKS / "matched_shot_commutator_krylov.json"
SENSITIVITY = BENCHMARKS / "matched_shot_commutator_krylov_floor20.json"
DOCUMENT = BENCHMARKS / "MATCHED_SHOT_COMMUTATOR_KRYLOV.md"
BEGIN = "<!-- generated by run_matched_shot_commutator_krylov.py --report; do not edit -->\n"
END = "<!-- end of generated tables -->\n"


@pytest.fixture(scope="module")
def records():
    return tuple(json.loads(path.read_text(encoding="utf-8")) for path in (PRIMARY, SENSITIVITY))


def test_the_document_embeds_exactly_the_generated_tables(records):
    text = DOCUMENT.read_text(encoding="utf-8")
    assert text.count(BEGIN) == 1 and text.count(END) == 1
    embedded = text.split(BEGIN, 1)[1].split(END, 1)[0]
    assert embedded == study.report(*records)


def test_the_records_come_from_one_clean_commit_and_differ_only_in_the_floor(records):
    primary, sensitivity = records
    for record in records:
        assert record["schema"] == study.SCHEMA
        assert record["metadata"]["git_dirty"] is False
    assert primary["metadata"]["git_sha"] == sensitivity["metadata"]["git_sha"]
    assert primary["design"]["floor_multiplier"] == study.FLOOR_MULTIPLIER
    assert sensitivity["design"]["floor_multiplier"] == 10 * study.FLOOR_MULTIPLIER
    a, b = (dict(record["design"]) for record in records)
    a.pop("floor_multiplier"), b.pop("floor_multiplier")
    assert a == b == {"seed_root": study.SEED_ROOT, "basis_sizes": list(study.BASIS_SIZES),
                      "budgets": list(study.BUDGETS), "replicas": study.REPLICAS,
                      "arms": list(study.ARMS), "chemical_accuracy": study.CHEMICAL_ACCURACY,
                      "complex_arms": list(study.COMPLEX_ARMS)}
    assert [s["key"] for s in primary["systems"]] == [s["key"] for s in study.SYSTEMS]
    assert [s["key"] for s in sensitivity["systems"]] == [s["key"] for s in study.SYSTEMS]


def test_the_records_are_complete_and_count_their_shots_as_declared(records):
    for record in records:
        for system in record["systems"]:
            # The noise-free part does not depend on the floor.
            assert system["target_index"] == 0
            for arm in study.ARMS:
                for size in study.BASIS_SIZES:
                    row = system["arms"][arm]["sizes"][str(size)]
                    if not row["available"]:
                        assert arm.endswith("acase") and row["exhausted_at"] < size
                        continue
                    assert row["measured_quantities"] == study.quantities(arm, size)
                    assert set(row["budgets"]) == {str(b) for b in study.BUDGETS}
                    for budget, cell in row["budgets"].items():
                        shots = int(budget) // row["measured_quantities"]
                        assert cell["shots_per_quantity"] == shots
                        if shots < 1:
                            assert cell["skipped"] is True
                            continue
                        assert cell["replicas"] == study.REPLICAS
                        assert cell["overlap_floor"] == pytest.approx(study.overlap_floor(
                            size, shots, record["design"]["floor_multiplier"],
                            complex_entries=arm in study.COMPLEX_ARMS))
    primary, sensitivity = records
    for a, b in zip(primary["systems"], sensitivity["systems"]):
        for arm in study.ARMS:
            assert a["arms"][arm]["labels"] == b["arms"][arm]["labels"]
            for size in study.BASIS_SIZES:
                left = a["arms"][arm]["sizes"][str(size)]
                right = b["arms"][arm]["sizes"][str(size)]
                assert left.get("exact_error") == right.get("exact_error")
