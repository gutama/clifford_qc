    """Generate LaTeX macros for every scalar reported in manuscript prose."""
    rows = record["rows"]
    part_a_rows = [r for r in rows if r["part"] == "A"]
    part_b_rows = [r for r in rows if r["part"] == "B"]
    part_a_map = {(r["case"], r["arm"]): r for r in summary["part_a"]}
    part_b_map = {(r["case"], r["regime"], r["arm"]): r for r in summary["part_b"]}
    p1a_cells = summary["criteria"]["P1a_weighted_vs_unweighted"]["cells"]
    p2_cells = summary["criteria"]["P2_stretched_rank_transfer"]["cells"]
    p3_cells = summary["criteria"]["P3_galic_noise_gate"]["cells"]
    width_rows = summary["criteria"]["width_guard_overhead"]

    passing_p1a = [c for c in p1a_cells if c["passed"]]
    min_p1a_med = min(c["shot_ratio"]["median_ratio"] for c in passing_p1a)
    max_p1a_med = max(c["shot_ratio"]["median_ratio"] for c in passing_p1a)
    min_p1a_speedup = min(1.0 / c["shot_ratio"]["mean_ratio"] for c in passing_p1a)
    max_p1a_speedup = max(1.0 / c["shot_ratio"]["mean_ratio"] for c in passing_p1a)

    # Look-by-look SE on lih_8q for the discrete-grid tie explanation.
    def _look_med_se(cname: str, arm: str, look_idx: int) -> tuple[float, float, float]:
        vals = [
            r["looks"][look_idx]["std_error"] * 1000.0
            for r in part_a_rows
            if r["case_name"] == cname and r["arm"] == arm and len(r["looks"]) > look_idx
        ]
        return float(np.median(vals)), float(min(vals)), float(max(vals))

    lih_si_fc_l0, _, _ = _look_med_se("lih_8q", "si_fc", 0)
    lih_ldf_fc_l0, _, _ = _look_med_se("lih_8q", "ldf_fc", 0)
    lih_si_fc_l2, lih_si_fc_l2_lo, lih_si_fc_l2_hi = _look_med_se("lih_8q", "si_fc", 2)
    lih_ldf_fc_l2, lih_ldf_fc_l2_lo, lih_ldf_fc_l2_hi = _look_med_se("lih_8q", "ldf_fc", 2)
    lih_si_qwc_l2, _, _ = _look_med_se("lih_8q", "si_qwc", 2)

